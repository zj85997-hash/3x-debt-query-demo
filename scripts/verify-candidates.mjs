import assert from 'node:assert/strict';
import {call,session} from './api-test.mjs';
const token=await session('candidate');
const {body:{policy}}=await call('/api/profiles');
const route='/api/candidate-search';
const check=(name,tail4)=>call(route,{name,tail4,policy,accepted:true},token);
assert.equal((await call(route,{name:'样例甲',tail4:'0067',policy,accepted:true})).status,401);
const one=await check(' 样例甲 ','００６７');
assert.equal(one.status,200);
assert.equal(one.body.state,'candidate');
assert.equal(one.body.candidateCount,1);
assert.equal(one.body.candidates[0].source_ref,'DEMO-FIX-001');
assert.equal(one.body.candidates[0].source_page,1);
const otherTail=await check('样例甲','7021');
assert.equal(otherTail.body.candidates[0].source_ref,'DEMO-FIX-002');
const collision=await check('样例重名','8042');
assert.equal(collision.body.state,'ambiguous');
assert.equal(collision.body.candidateCount,2);
assert.equal(collision.body.candidates.length,0);
assert.equal((await check('样例甲','9999')).body.state,'empty');
assert.equal((await check('样例乙','351x')).body.candidateCount,1);
assert.equal((await check('普通姓名','0067')).status,400);
assert.equal((await check('样例甲','67')).status,400);
assert.equal((await call(route,{name:'样例甲',tail4:'0067',policy,accepted:false},token)).status,400);
console.log('PASS: PDF来源页、单候选、重名冲突、未命中、尾号前导零、末位X、模拟输入与授权校验');
